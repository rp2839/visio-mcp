#!/usr/bin/env node
// Generates TypeScript and C# DTOs from the contracts/ JSON Schema bundle.
// Supports the subset the bundle uses: $ref, object/properties/required, allOf merge,
// additionalProperties maps, const, enum, oneOf/anyOf unions (discriminated or nullable),
// arrays and primitives. Runtime validation stays with Ajv/semantic checks.
// Usage: node tools/generate-contracts.mjs [--check]
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const files = ['document', 'operations', 'protocol'];
const defs = new Map(); // name -> schema
for (const f of files) {
  const schema = JSON.parse(readFileSync(join(root, 'contracts', `${f}.schema.json`), 'utf8'));
  for (const [name, def] of Object.entries(schema.$defs)) {
    if (defs.has(name)) throw new Error(`duplicate $def name ${name} across bundle`);
    defs.set(name, def);
  }
}
const refName = (ref) => ref.split('/').pop();
const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const isNull = (s) => s.type === 'null';

/** Merge allOf object parts with the schema's own properties. */
function objectParts(schema) {
  const props = {};
  const required = new Set();
  for (const part of schema.allOf ?? []) {
    const p = part.$ref ? defs.get(refName(part.$ref)) : part;
    if (!p.properties) continue;
    Object.assign(props, p.properties);
    for (const r of p.required ?? []) required.add(r);
  }
  Object.assign(props, schema.properties ?? {});
  for (const r of schema.required ?? []) required.add(r);
  return { props, required };
}

// ---------------- TypeScript ----------------
function ts(schema, indent = '') {
  if (schema.$ref) return refName(schema.$ref);
  if ('const' in schema) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(' | ');
  const union = schema.oneOf ?? schema.anyOf;
  if (union && !schema.properties) return union.map((s) => ts(s, indent)).join(' | ');
  switch (schema.type) {
    case 'string': return 'string';
    case 'number': case 'integer': return 'number';
    case 'boolean': return 'boolean';
    case 'null': return 'null';
    case 'array': return `${wrap(ts(schema.items, indent))}[]`;
  }
  if (schema.type === 'object' || schema.properties || schema.allOf) {
    const { props, required } = objectParts(schema);
    const keys = Object.keys(props);
    if (keys.length === 0) {
      return schema.additionalProperties && typeof schema.additionalProperties === 'object'
        ? `Record<string, ${ts(schema.additionalProperties, indent)}>` : 'Record<string, unknown>';
    }
    const inner = indent + '  ';
    const lines = keys.map((k) => `${inner}${k}${required.has(k) ? '' : '?'}: ${ts(props[k], inner)};`);
    return `{\n${lines.join('\n')}\n${indent}}`;
  }
  return 'unknown';
}
const wrap = (t) => (/[|&]/.test(t) && !t.startsWith('{') ? `(${t})` : t);

let tsOut = `// GENERATED by tools/generate-contracts.mjs from contracts/*.schema.json. Do not edit.\n/* eslint-disable */\n\n`;
for (const [name, def] of defs) {
  if (def.description) tsOut += `/** ${def.description} */\n`;
  tsOut += `export type ${name} = ${ts(def)};\n\n`;
}

// ---------------- C# ----------------
const csTypes = [];
const csEmitted = new Set();
const unionMembers = new Map(); // member name -> { base, discriminatorProp, value }
for (const [name, def] of defs) {
  if (def.discriminator && def.oneOf) {
    for (const m of def.oneOf) {
      const member = refName(m.$ref);
      const md = defs.get(member);
      const { props } = objectParts(md);
      const value = props[def.discriminator.propertyName]?.const;
      unionMembers.set(member, { base: name, prop: def.discriminator.propertyName, value });
    }
  }
}

function isNamedRecord(def) {
  if (def.discriminator && def.oneOf) return true;
  if (!(def.type === 'object' || def.properties || def.allOf)) return false;
  return Object.keys(objectParts(def).props).length > 0;
}

function csType(schema, owner, prop) {
  if (schema.$ref) {
    const name = refName(schema.$ref);
    const def = defs.get(name);
    // Primitive aliases, maps and arrays collapse to their C# shape; records keep the name.
    return isNamedRecord(def) ? name : csType({ ...def, description: undefined }, owner, prop);
  }
  if ('const' in schema) return typeof schema.const === 'number' ? 'int' : 'string';
  if (schema.enum) return 'string';
  const union = schema.anyOf ?? schema.oneOf;
  if (union && !schema.properties) {
    // Nullable patch field or free union: keep exact JSON (null vs absent) as JsonElement.
    return 'JsonElement';
  }
  switch (schema.type) {
    case 'string': return 'string';
    case 'number': return 'double';
    case 'integer': return 'long';
    case 'boolean': return 'bool';
    case 'array': return `List<${csType(schema.items, owner, prop)}>`;
  }
  if (schema.type === 'object' || schema.properties) {
    const { props } = objectParts(schema);
    if (Object.keys(props).length === 0) {
      if (schema.additionalProperties && typeof schema.additionalProperties === 'object')
        return `Dictionary<string, ${csType(schema.additionalProperties, owner, prop)}>`;
      return 'JsonElement';
    }
    const nested = owner + pascal(prop);
    emitRecord(nested, schema);
    return nested;
  }
  return 'JsonElement';
}

function emitRecord(name, schema) {
  if (csEmitted.has(name)) return;
  csEmitted.add(name);
  const { props, required } = objectParts(schema);
  const member = unionMembers.get(name);
  const lines = [];
  if (schema.description) lines.push(`/// <summary>${schema.description.replace(/&/g, '&amp;').replace(/</g, '&lt;')}</summary>`);
  lines.push(`public sealed partial record ${name}${member ? ` : ${member.base}` : ''}`);
  lines.push('{');
  for (const [k, ps] of Object.entries(props)) {
    if (member && k === member.prop) continue; // discriminator handled by [JsonPolymorphic]
    const t = csType(ps, name, k);
    const isValueJson = t === 'JsonElement';
    const opt = !required.has(k);
    const nullable = opt && !isValueJson ? '?' : '';
    const attrs = [`[JsonPropertyName("${k}")]`];
    if (opt) attrs.push(isValueJson ? '[JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingDefault)]' : '[JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]');
    let init = '';
    if (!opt && 'const' in ps) init = ` = ${JSON.stringify(ps.const)};`;
    else if (!opt && !isValueJson && /^(string)$/.test(t)) init = ' = "";';
    else if (!opt && /^(List|Dictionary)</.test(t)) init = ' = new();';
    else if (!opt && !['double', 'long', 'bool', 'int', 'JsonElement'].includes(t)) init = ' = null!;';
    const propName = pascal(k) === name ? pascal(k) + 'Value' : pascal(k);
    lines.push(`    ${attrs.join(' ')} public ${t}${nullable} ${propName} { get; init; }${init}`);
  }
  lines.push('}');
  csTypes.push(lines.join('\n'));
}

for (const [name, def] of defs) {
  if (def.discriminator && def.oneOf) {
    const p = def.discriminator.propertyName;
    const derived = def.oneOf.map((m) => refName(m.$ref)).map((member) => `[JsonDerivedType(typeof(${member}), "${unionMembers.get(member).value}")]`);
    csTypes.push(`[JsonPolymorphic(TypeDiscriminatorPropertyName = "${p}", UnknownDerivedTypeHandling = JsonUnknownDerivedTypeHandling.FailSerialization)]\n${derived.join('\n')}\npublic abstract partial record ${name};`);
    continue;
  }
  if (isNamedRecord(def)) {
    if (name === 'ElementCommon') continue; // flattened into each element record
    emitRecord(name, def);
  }
}

const csOut = `// GENERATED by tools/generate-contracts.mjs from contracts/*.schema.json. Do not edit.
#nullable enable
using System.Collections.Generic;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace Diagram.Core.Contracts;

${csTypes.join('\n\n')}
`;

// ---------------- precompiled validators (no runtime eval under the editor CSP) ----------------
const { createRequire } = await import('node:module');
const req = createRequire(join(root, 'src/web/package.json'));
const Ajv2020 = req('ajv/dist/2020').default;
const standalone = req('ajv/dist/standalone').default;
const addFormats = req('ajv-formats').default;
const ajv = new Ajv2020({ strict: false, discriminator: true, code: { source: true, esm: true } });
addFormats(ajv);
for (const f of files) ajv.addSchema(JSON.parse(readFileSync(join(root, 'contracts', `${f}.schema.json`), 'utf8')));
const base = 'https://agentic-diagram.invalid/schema/';
const validatorRefs = {
  validateDocumentSchema: `${base}document.json`,
  validateElementSchemaFn: `${base}document.json#/$defs/Element`,
  validateOperationBatch: `${base}operations.json#/$defs/OperationBatch`,
  validateRequestEnvelope: `${base}protocol.json#/$defs/RequestEnvelope`,
  validateMutationRequest: `${base}protocol.json#/$defs/MutationRequest`,
  validateScriptRequest: `${base}protocol.json#/$defs/ScriptRequest`,
};
let validatorCode = standalone(ajv, validatorRefs).replace(/^"use strict";/, '');
const requires = [...new Set([...validatorCode.matchAll(/require\("([^"]+)"\)/g)].map((m) => m[1]))];
requires.forEach((spec, i) => { validatorCode = validatorCode.split(`require("${spec}")`).join(`__r${i}`); });
const validatorsOut = `// GENERATED by tools/generate-contracts.mjs (Ajv standalone). Do not edit.\n/* eslint-disable */\n`
  + requires.map((spec, i) => `import * as __ns${i} from "${spec}";\n`).join('')
  + `// CommonJS interop: bundlers and Node expose module.exports either directly or as .default.\n`
  + `const __interop = (ns) => (ns && ns.default && typeof ns.default === 'object' ? ns.default : ns);\n`
  + requires.map((_, i) => `const __r${i} = __interop(__ns${i});\n`).join('') + validatorCode + '\n';

const targets = [
  [join(root, 'src/web/src/contracts/validators.js'), validatorsOut],
  [join(root, 'src/web/src/contracts/generated.ts'), tsOut],
  [join(root, 'src/Diagram.Core.Contracts/Generated/Contracts.g.cs'), csOut],
];
const check = process.argv.includes('--check');
let stale = false;
for (const [path, text] of targets) {
  if (check) {
    let current = '';
    try { current = readFileSync(path, 'utf8'); } catch { /* missing */ }
    if (current !== text) { console.error(`stale: ${path}`); stale = true; }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
    console.log(`wrote ${path}`);
  }
}
if (stale) process.exit(1);
