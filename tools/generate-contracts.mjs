// Generates the TypeScript and C# DTOs from the schema bundle in contracts/.
// One source, two languages: no handwritten wire types. Run: node tools/generate-contracts.mjs [--check]
// --check regenerates in memory and fails if the committed output differs (used by tests/CI).
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const files = ['document', 'operations', 'protocol', 'preferences'];
const defs = new Map(); // name -> { schema, file }
for (const f of files) {
  const s = JSON.parse(readFileSync(resolve(root, `contracts/${f}.schema.json`), 'utf8'));
  for (const [name, schema] of Object.entries(s.$defs)) {
    if (defs.has(name)) throw new Error(`duplicate definition ${name}`);
    defs.set(name, { schema, file: f });
  }
}

const refName = r => r.slice(r.lastIndexOf('/') + 1);
const pascal = s => s[0].toUpperCase() + s.slice(1);
const isUnion = s => Array.isArray(s.oneOf) && s['x-discriminator'];

// Union membership, with the discriminator value of each member and the language-level member name.
const memberOf = new Map(); // member def name -> { union, prop, value }
const typeName = name => (memberOf.get(name)?.prop === 'op' ? name + 'Op' : name);
for (const [name, { schema }] of defs) {
  if (!isUnion(schema)) continue;
  const prop = schema['x-discriminator'];
  for (const m of schema.oneOf) {
    const mname = refName(m.$ref);
    const value = defs.get(mname).schema.properties[prop].const;
    memberOf.set(mname, { union: name, prop, value });
  }
}

const primitiveDef = s => !s.properties && !s.oneOf && s.type !== 'object' && s.type !== 'array';

// ---------------------------------------------------------------- TypeScript
function ts(s, indent = '') {
  if (s.$ref) return typeName(refName(s.$ref));
  if ('const' in s) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map(v => JSON.stringify(v)).join(' | ');
  if (Array.isArray(s.type)) return s.type.map(t => ts({ ...s, type: t })).join(' | ');
  switch (s.type) {
    case 'string': return 'string';
    case 'number': case 'integer': return 'number';
    case 'boolean': return 'boolean';
    case 'null': return 'null';
    case 'array': return `${wrap(ts(s.items, indent))}[]`;
    case 'object':
      if (s.properties) return objectTs(s, indent);
      if (s.additionalProperties && typeof s.additionalProperties === 'object') return `Record<string, ${ts(s.additionalProperties, indent)}>`;
      return 'Record<string, unknown>';
    default: return 'unknown';
  }
}
const wrap = t => (/[|&]/.test(t) && !t.startsWith('{') ? `(${t})` : t);
function objectTs(s, indent) {
  const req = new Set(s.required ?? []);
  const lines = Object.entries(s.properties).map(([k, v]) => `${indent}  ${k}${req.has(k) ? '' : '?'}: ${ts(v, indent + '  ')};`);
  return `{\n${lines.join('\n')}\n${indent}}`;
}
function emitTs() {
  const out = ['// Generated by tools/generate-contracts.mjs from contracts/*.schema.json. Do not edit.', ''];
  for (const [name, { schema }] of defs) {
    const n = typeName(name);
    if (isUnion(schema)) out.push(`export type ${n} = ${schema.oneOf.map(m => typeName(refName(m.$ref))).join(' | ')};`, '');
    else if (schema.properties) out.push(`export interface ${n} ${objectTs(schema, '')}`, '');
    else out.push(`export type ${n} = ${ts(schema)};`, '');
  }
  out.push('export function createPreferencesDefaults(): AppPreferences { return ' + JSON.stringify(defs.get('AppPreferences').schema.default) + '; }');
  return out.join('\n');
}

// ------------------------------------------------------------------------ C#
function cs(s, optional = false) {
  let t;
  if (s.$ref) {
    const d = defs.get(refName(s.$ref)).schema;
    t = primitiveDef(d) ? cs(d) : typeName(refName(s.$ref));
  } else if ('const' in s) t = typeof s.const === 'number' ? 'int' : typeof s.const === 'boolean' ? 'bool' : 'string';
  else if (s.enum) t = 'string';
  else if (Array.isArray(s.type)) {
    const nonNull = s.type.filter(x => x !== 'null');
    t = cs({ ...s, type: nonNull[0] });
    if (s.type.includes('null')) optional = true;
  } else {
    switch (s.type) {
      case 'string': t = 'string'; break;
      case 'integer': t = 'int'; break;
      case 'number': t = 'double'; break;
      case 'boolean': t = 'bool'; break;
      case 'array': t = `IReadOnlyList<${cs(s.items)}>`; break;
      case 'object':
        t = s.additionalProperties && typeof s.additionalProperties === 'object' ? `IReadOnlyDictionary<string, ${cs(s.additionalProperties)}>` : 'JsonObject';
        break;
      default: t = 'JsonElement';
    }
  }
  return optional && !t.endsWith('?') ? t + '?' : t;
}
function emitCs() {
  const out = [
    '// Generated by tools/generate-contracts.mjs from contracts/*.schema.json. Do not edit.',
    '#nullable enable',
    'using System.Text.Json;',
    'using System.Text.Json.Nodes;',
    'using System.Text.Json.Serialization;',
    '',
    'namespace Diagram.Core.Contracts;',
    '',
    '/// <summary>Serializer settings every consumer of these DTOs must use: polymorphic discriminators may appear in any property order, unknown members are errors.</summary>',
    'public static class ContractJson',
    '{',
    '    public static JsonSerializerOptions Options { get; } = new(JsonSerializerDefaults.Web)',
    '    {',
    '        AllowOutOfOrderMetadataProperties = true,',
    '        UnmappedMemberHandling = JsonUnmappedMemberHandling.Disallow,',
    '        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,',
    '    };',
    '}',
    '',
  ];
  for (const [name, { schema }] of defs) {
    const n = typeName(name);
    if (isUnion(schema)) {
      const prop = schema['x-discriminator'];
      out.push(`[JsonPolymorphic(TypeDiscriminatorPropertyName = "${prop}")]`);
      for (const m of schema.oneOf) {
        const mn = refName(m.$ref);
        out.push(`[JsonDerivedType(typeof(${typeName(mn)}), ${JSON.stringify(memberOf.get(mn).value)})]`);
      }
      out.push(`public abstract record ${n};`, '');
    } else if (schema.properties) {
      const member = memberOf.get(name);
      const req = new Set(schema.required ?? []);
      const props = [];
      for (const [k, v] of Object.entries(schema.properties)) {
        if (member && k === member.prop) continue; // carried by the base type's discriminator
        const pn = pascal(k);
        const optional = !req.has(k);
        const type = cs(v, optional);
        const attrs = `[JsonPropertyName("${k}")]`;
        if ('const' in v && !optional) props.push(`    ${attrs} public ${type} ${pn} { get; init; } = ${JSON.stringify(v.const)};`);
        else props.push(`    ${attrs} public ${optional ? '' : 'required '}${type} ${pn} { get; init; }`);
      }
      const base = member ? ` : ${typeName(member.union)}` : '';
      out.push(`public sealed record ${n}${base}${props.length ? `\n{\n${props.join('\n')}\n}` : ';'}`, '');
    }
  }
  return out.join('\n');
}

// ---------------------------------------------------------------- precompiled validators
// Ajv normally builds validators with new Function(), which a CSP without 'unsafe-eval' forbids. The page ships these
// precompiled (standalone) validators instead, so no code is generated at runtime.
// Only what the page validates at runtime: whole documents and requests, and each operation (for precise error messages).
const VALIDATED = [
  'AppPreferences', 'CapturedDocumentDefaults', 'DiagramDocument', 'MutationRequest', 'ScriptRequest', 'UndoRequest', 'RequestEnvelope', 'Operation',
  'CreateShape', 'CreateText', 'CreateImage', 'CreateConnector', 'Set', 'Move', 'Resize', 'Rotate', 'Delete', 'RegisterAsset', 'SetPage', 'SetRoutingDefaults', 'Beautify',
  'Duplicate', 'Group', 'Ungroup', 'Align', 'Distribute', 'SetGap', 'Reorder', 'AddPage', 'ReorderPage', 'DuplicatePage', 'DeletePage',
  'AddLayer', 'SetLayer', 'AssignLayers', 'DeleteLayer', 'SetAsset', 'RemoveAsset', 'ReplaceAsset',
];

function emitValidators() {
  const req = createRequire(resolve(root, 'src/web/package.json'));
  const Ajv2020 = req('ajv/dist/2020').default;
  const standaloneCode = req('ajv/dist/standalone').default;
  const ajv = new Ajv2020({ allErrors: false, strict: false, code: { source: true, esm: true } });
  const ids = {};
  for (const f of files) {
    const s = JSON.parse(readFileSync(resolve(root, `contracts/${f}.schema.json`), 'utf8'));
    ajv.addSchema(s);
    ids[f] = s.$id;
  }
  const exportsMap = {};
  for (const name of VALIDATED) exportsMap[name] = `${ids[defs.get(name).file]}#/$defs/${name}`;
  let code = standaloneCode(ajv, exportsMap);
  // The generated module is ESM but calls require() for Ajv's two tiny runtime helpers. Importing those CommonJS files broke under the
  // bundler's default-import interop (found in the real WebView2 run), so inline equivalent helpers instead.
  const helpers = {
    'ajv/dist/runtime/ucs2length': (name) => `const ${name} = (str) => { let length = 0; const len = str.length; let pos = 0; let value; while (pos < len) { length++; value = str.charCodeAt(pos++); if (value >= 0xd800 && value <= 0xdbff && pos < len) { value = str.charCodeAt(pos); if ((value & 0xfc00) === 0xdc00) pos++; } } return length; };`,
    'ajv/dist/runtime/equal': (name) => `const ${name} = (a, b) => { if (a === b) return true; if (a && b && typeof a === "object" && typeof b === "object") { if (Array.isArray(a)) { if (!Array.isArray(b) || a.length !== b.length) return false; for (let i = 0; i < a.length; i++) if (!${name}(a[i], b[i])) return false; return true; } if (Array.isArray(b)) return false; const ka = Object.keys(a); if (ka.length !== Object.keys(b).length) return false; for (const k of ka) if (!Object.prototype.hasOwnProperty.call(b, k) || !${name}(a[k], b[k])) return false; return true; } return a !== a && b !== b; };`,
  };
  const preamble = [];
  code = code.replace(/const (func\d+) = require\("([^"]+)"\)\.default;/g, (_m, name, path) => {
    if (!helpers[path]) throw new Error(`unexpected runtime helper ${path}`);
    preamble.push(helpers[path](name));
    return '';
  });
  code = preamble.join('\n') + '\n' + code;
  code = `// Generated by tools/generate-contracts.mjs from contracts/*.schema.json. Do not edit.\n// @ts-nocheck\n` + code;
  const names = VALIDATED;
  const dts = [
    '// Generated by tools/generate-contracts.mjs. Do not edit.',
    "import type { ErrorObject } from 'ajv';",
    'export type ValidateFn = ((data: unknown) => boolean) & { errors?: ErrorObject[] | null };',
    ...names.map(n => `export const ${n}: ValidateFn;`),
  ].join('\n');
  return { code, dts };
}
const validators = emitValidators();

const targets = [
  [resolve(root, 'src/web/src/model/validators.generated.js'), validators.code],
  [resolve(root, 'src/web/src/model/validators.generated.d.ts'), validators.dts],
  [resolve(root, 'src/web/src/contracts/generated.ts'), emitTs()],
  [resolve(root, 'src/Diagram.Core.Contracts/Generated/Contracts.g.cs'), emitCs()],
];
const check = process.argv.includes('--check');
let stale = false;
for (const [path, text] of targets) {
  const body = text.replace(/\r?\n/g, '\n') + '\n';
  if (check) {
    const cur = existsSync(path) ? readFileSync(path, 'utf8').replace(/\r\n/g, '\n') : '';
    if (cur !== body) { console.error(`stale: ${path}`); stale = true; }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, body);
    console.log(`wrote ${path}`);
  }
}
if (stale) process.exit(1);
